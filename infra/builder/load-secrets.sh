#!/usr/bin/env bash
# ============================================================================
# Gives PHP the app's config path and secrets. Secrets live in
# /etc/rowancopy/secrets.env (one NAME=value per line, root-only), never in
# the app folder or Git. Run after editing that file:
#   sudo bash infra/builder/load-secrets.sh
# ============================================================================
set -euo pipefail
[ "$(id -u)" -eq 0 ] || { echo "Run with sudo." >&2; exit 1; }
PHP_VERSION=${PHP_VERSION:-8.3}
src=/etc/rowancopy/secrets.env
out=/etc/php/$PHP_VERSION/fpm/pool.d/zz-rowancopy.conf
umask 077
{
  echo "; Generated by infra/builder/load-secrets.sh from $src. Don't edit; edit that file and rerun."
  echo "[www]"
  echo "env[RC_CONFIG] = /etc/rowancopy/config.php"
  echo "php_admin_value[upload_max_filesize] = 10M"
  echo "php_admin_value[post_max_size] = 12M"
  if [ -f "$src" ]; then
    while IFS= read -r line || [ -n "$line" ]; do
      case "$line" in ''|\#*) continue ;; esac
      name=${line%%=*}; value=${line#*=}
      [[ "$name" =~ ^[A-Z][A-Z0-9_]*$ ]] || { echo "Skipping invalid line in $src: $name" >&2; continue; }
      value=${value//\"/}
      printf 'env[%s] = "%s"\n' "$name" "$value"
    done < "$src"
  fi
} > "$out.tmp"
mv "$out.tmp" "$out"
chmod 600 "$out"
"php-fpm$PHP_VERSION" -t >/dev/null 2>&1 || { echo "PHP-FPM rejected the generated config; check $src." >&2; exit 1; }
systemctl reload "php$PHP_VERSION-fpm" 2>/dev/null || systemctl restart "php$PHP_VERSION-fpm"
echo "Loaded $(grep -c '^env\[' "$out") environment value(s) into PHP (including RC_CONFIG)."
